    /**
     * @return iterable<string, array{\Closure(SiteWriter): void}>
     */
    public static function siteWriterCalls(): iterable
    {
        yield 'write' => [static fn(SiteWriter $writer) => $writer->write('main', ['rootPageId' => 99])];
        yield 'write a new site' => [static fn(SiteWriter $writer) => $writer->createNewBasicSite('written', 99, '/')];
        yield 'writeSettings' => [static fn(SiteWriter $writer) => $writer->writeSettings('main', ['written' => true])];
        yield 'rename' => [static fn(SiteWriter $writer) => @$writer->rename('main', 'renamed')];
        yield 'delete' => [static fn(SiteWriter $writer) => $writer->delete('main')];
    }

    /**
     * @param \Closure(SiteWriter): void $call
     */
    #[Test]
    #[DataProvider('siteWriterCalls')]
    public function siteWriterOfTypo3DoesNotWriteIntoTheProject(\Closure $call): void
    {
        $before = self::filesOf($this->projectSitesPath());

        $failed = false;
        try {
            // as TYPO3 gets it: from the container and through makeInstance()
            $call(GeneralUtility::makeInstance(SiteWriter::class));
        } catch (\Throwable) {
            $failed = true;
        }

        self::assertTrue($failed, 'The write did not fail.');
        self::assertSame($this->get(SiteWriter::class), GeneralUtility::makeInstance(SiteWriter::class));
        self::assertSame($before, self::filesOf($this->projectSitesPath()));
    }

    /**
     * @return array<string, string> path => hash of the content
     */
    private static function filesOf(string $directory): array
    {
        $files = [];
        $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($directory, \FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            if ($file instanceof \SplFileInfo && $file->isFile()) {
                $files[$file->getPathname()] = (string)sha1_file($file->getPathname());
            }
        }
        ksort($files);

        return $files;
    }

    #[Test]
    public function newRootPageWritesNoSiteConfigurationIntoTheProject(): void
    {
        // TYPO3 would create a site "autogenerated-..." for each of them, in the linked config/sites
        PageFactory::new()->under(0)->title('At the top level')->create();
        PageFactory::new()->in($this->site())->title('Second root')->siteRoot()->slug('/second-root')->create();

        // scandir() sorts by the locale: "_shared" comes first on macOS and last on Linux
        $directories = array_values(array_diff((array)scandir($this->projectSitesPath()), ['.', '..']));
        sort($directories, SORT_STRING);
        self::assertSame(['_shared', 'main', 'second'], $directories);
        self::assertSame(['main', 'second'], array_keys($this->get(SiteFinder::class)->getAllSites(false)));
    }

    #[Test]
    public function projectFilesAreLookedUpBelowTheProjectDirectoryAndNotBelowTheWebRoot(): void
    {
        $projectPath = dirname(__DIR__, 3);
        // the web root of this package is two directories below the project directory
        self::assertSame($projectPath . '/.Build/public/', ORIGINAL_ROOT);

        self::assertSame($projectPath . '/config/system/settings.php', $this->projectSystemSettingsPath());
        // FixtureTestCase overrides the path of the sites: this is the one of DomTestCase
        self::assertSame($projectPath . '/config/sites', DomTestCase::projectSitesPath());
    }

