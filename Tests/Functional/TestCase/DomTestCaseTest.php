    #[Test]
    public function pageTreeWithoutDeclarationIsTheRootPageAndAPagePerPageIdSetting(): void
    {
        $pages = [];
        foreach ($this->rows('pages') as $row) {
            $pages[(int)$row['uid']] = [(int)$row['pid'], $row['title'], (int)$row['is_siteroot'], (int)$row['nav_hide']];
        }

        self::assertSame(
            [
                1 => [0, 'main', 1, 0],
                20 => [1, 'footer', 0, 1],
                30 => [1, 'storage.records', 0, 1],
            ],
            $pages,
        );
        self::assertSame(1, $this->pageTree()->rootPage()->uid());
        self::assertSame(20, $this->pageTree()->page('footer')->uid());
        self::assertSame(30, $this->pageTree()->page('storage.records')->uid());
        self::assertFalse($this->pageTree()->hasPage('notConfigured'));
        self::assertFalse($this->pageTree()->hasPage('itemsPerPage'));
    }

    #[Test]
    public function visitRendersThePageThroughTheFrontend(): void
    {
        $content = ContentFactory::new()->header('Hello & welcome')->bodytext('Some text');
        $page = PageFactory::new()->in($this->site())->title('Products')->with($content)->create();

        $document = $this->visit($page);

        self::assertSame('Products', self::textOf($document->querySelector('h1')));
        self::assertSame('Hello & welcome', self::textOf($document->querySelector('#c' . $content->uid())));
        self::assertSame('Some text', self::textOf($document->querySelector('main section p')));
    }

    #[Test]
    public function visitTakesAUrl(): void
    {
        PageFactory::new()->in($this->site())->title('Products')->slug('/products')->create();

        self::assertSame('Products', self::textOf($this->visit('https://main.phixture.test/products')->querySelector('h1')));
    }

    #[Test]
    public function contentIsRenderedInTheOrderOfTheTest(): void
    {
        $page = PageFactory::new()->in($this->site())->with(
            ContentFactory::new()->header('First'),
            ContentFactory::new()->header('Second'),
            ContentFactory::new()->header('Third'),
        )->create();

        $headers = array_map(self::textOf(...), $this->visit($page)->querySelectorAll('main h2'));

        self::assertSame(['First', 'Second', 'Third'], $headers);
    }

    #[Test]
    public function visitFailsOnAnyStatusBut200(): void
    {
        $page = PageFactory::new()->in($this->site())->title('Hidden page')->hidden()->create();

        try {
            $this->visit($page);
        } catch (AssertionFailedError $failure) {
            self::assertStringContainsString('Status 404', $failure->getMessage());
            self::assertStringContainsString('Pages in the database:', $failure->getMessage());
            self::assertStringContainsString('"title":"Hidden page"', $failure->getMessage());

            return;
        }
        self::fail('visit() did not fail for a hidden page.');
    }

    #[Test]
    public function visitResponseReturnsTheResponseOfAnyStatus(): void
    {
        $response = $this->visitResponse('https://main.phixture.test/no-such-page');

        self::assertSame(404, $response->getStatusCode());
    }

    #[Test]
    public function visitResponseTakesAPageAndSendsRequestHeaders(): void
    {
        $page = PageFactory::new()->in($this->site())->create();

        $response = $this->visitResponse($page, ['x-phixture' => 'sent by the test']);

        self::assertSame(200, $response->getStatusCode());
        self::assertSame(
            'sent by the test',
            self::textOf(HtmlNode::fromHtml((string)$response->getBody())->querySelector('aside')),
        );
    }

    #[Test]
    public function textOfCollapsesWhitespace(): void
    {
        $document = HtmlNode::fromHtml("<p>  One\n   two\t<b>three</b>  </p>");

        self::assertSame('One two three', self::textOf($document->querySelector('p')));
    }

